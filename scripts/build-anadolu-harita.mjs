/**
 * build-anadolu-harita.mjs — /anadolu haritası için Türkiye sınır path data üretici.
 * (brief-anadolu-yolculuk.md — harita kalitesi gereksinimi.)
 *
 * Kaynak: datasets/geo-countries (Natural Earth derivative, public domain CC0).
 * https://github.com/datasets/geo-countries
 *
 * Sadeleştirme: Douglas-Peucker (eps=0.025° ≈ 2.5km) — Avrupa yakası (Trakya) ayrı
 * polygon olarak korunur, Ege çıkıntıları (Çanakkale, İzmir civarı) görünür kalır,
 * kıyı titremesi temizlenir. 3050 + 495 + 34 pt → ~428 + 61 + 8 pt.
 *
 * Projeksiyon: Mercator (mid-lat enlemler için kıyı oranı korunur), viewBox 1000×420.
 * Bounds padding ile (lon 25.5..45.2, lat 35.5..42.6) — Yanartaş (Çıralı, lat 36.43)
 * alt kenara yakın ama içeride.
 *
 * Re-run: indirilen geojson 14MB; bir kere indirilir, tekrar üretim eps değiştiğinde.
 *   curl -sL https://raw.githubusercontent.com/datasets/geo-countries/master/data/countries.geojson -o /tmp/countries.geojson
 *   node scripts/build-anadolu-harita.mjs > src/components/anadolu-harita-data.ts
 */
import fs from 'node:fs';

const GEOJSON_PATH = process.env.GEOJSON_PATH ?? '/tmp/countries.geojson';
const data = JSON.parse(fs.readFileSync(GEOJSON_PATH, 'utf-8'));
const tr = data.features.find(f => f.properties['ISO3166-1-Alpha-3'] === 'TUR');
if (!tr) {
  console.error('TUR feature bulunamadı. ' + GEOJSON_PATH + ' eksik veya hatalı.');
  process.exit(1);
}

function perpDist(p, a, b) {
  const [x, y] = p, [x1, y1] = a, [x2, y2] = b;
  const dx = x2 - x1, dy = y2 - y1;
  const lenSq = dx * dx + dy * dy;
  if (lenSq === 0) return Math.hypot(x - x1, y - y1);
  const t = Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / lenSq));
  const px = x1 + t * dx, py = y1 + t * dy;
  return Math.hypot(x - px, y - py);
}

function douglasPeucker(pts, eps) {
  if (pts.length < 3) return pts;
  const keep = new Array(pts.length).fill(false);
  keep[0] = true;
  keep[pts.length - 1] = true;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [i, j] = stack.pop();
    let maxD = 0, maxK = -1;
    for (let k = i + 1; k < j; k++) {
      const d = perpDist(pts[k], pts[i], pts[j]);
      if (d > maxD) { maxD = d; maxK = k; }
    }
    if (maxD > eps) {
      keep[maxK] = true;
      stack.push([i, maxK], [maxK, j]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const BB = { lonMin: 25.5, lonMax: 45.2, latMin: 35.5, latMax: 42.6 };
const VB = { w: 1000, h: 420 };
const EPS = 0.012; // ~1.3 km — Karaburun/Çeşme yarımadası + Bodrum/Datça çıkıntıları korunur,
                   // ilk pas eps=0.025 Urla'yı (AÇILIŞ noktası) sınır dışına bırakmıştı.

function mercY(lat) {
  return Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI / 180) / 2));
}
const yMaxM = mercY(BB.latMax);
const yMinM = mercY(BB.latMin);

function project([lon, lat]) {
  const x = (lon - BB.lonMin) / (BB.lonMax - BB.lonMin) * VB.w;
  const yM = mercY(lat);
  const y = (yMaxM - yM) / (yMaxM - yMinM) * VB.h;
  return [x, y];
}

const paths = [];
for (const poly of tr.geometry.coordinates) {
  for (let r = 0; r < poly.length; r++) {
    const ring = poly[r];
    // 30 puan altı: küçük adacıklar (görsel gürültü) — atla.
    if (ring.length < 30) continue;
    const simplified = douglasPeucker(ring, EPS);
    const projected = simplified.map(project);
    let d = '';
    for (let i = 0; i < projected.length; i++) {
      const [x, y] = projected[i];
      d += (i === 0 ? 'M' : 'L') + x.toFixed(1) + ',' + y.toFixed(1);
    }
    d += 'Z';
    paths.push(d);
    console.error(`ring ${r}: ${ring.length} → ${simplified.length} pts`);
  }
}

let out = '';
out += '// Auto-generated by scripts/build-anadolu-harita.mjs from Natural Earth (datasets/geo-countries, public domain CC0).\n';
out += `// Douglas-Peucker simplify eps=${EPS}° (~2.5km), Mercator projeksiyon, viewBox ${VB.w}×${VB.h}.\n`;
out += `// ${paths.length} ring: anatolia + trakya + kuzey-Ege adacığı. Bounds: ${JSON.stringify(BB)}.\n`;
out += '// Üretim: node scripts/build-anadolu-harita.mjs > src/components/anadolu-harita-data.ts\n';
out += '\n';
out += `export const TURKEY_VIEWBOX = '0 0 ${VB.w} ${VB.h}';\n`;
out += '\n';
out += 'export const TURKEY_PATHS = [\n';
for (const p of paths) out += '  ' + JSON.stringify(p) + ',\n';
out += '];\n';

process.stdout.write(out);
